package httpv1

import (
	"github.com/mondegor/go-components/mrauth/entity"
)

// isSettingsPending - сообщает, что настройки, сохранённые в профиле, ещё не попали
// в предъявленный access-токен: язык или часовой пояс профиля отличается от зафиксированного
// в области действия этого токена. Признак вычисляется на каждый запрос, поэтому после
// продления сессии он гаснет сам, без отдельной уборки, а у двух клиентов с токенами разного
// возраста ответы честно различаются.
//
// Язык и пояс проверяются оба: сохраняются они одним запросом (см. model.ChangeSettingsRequest),
// но измениться может любой из них по отдельности, и смена только языка - обычное дело.
//
// Оба значения токена берутся из внутренних заголовков (см. parser.User.LangCode
// и parser.User.TimeZoneName): на авторизованных маршрутах их заполняет middleware
// из области действия токена, а на гостевых срезает, поэтому подставить их клиент не может.
//
// Разовое переопределение через ?lang и ?tz сюда не попадает намеренно: эти параметры
// читают ParserLocale и ParserTimeZone, а не ParserUser. Признак описывает токен, а не
// конкретный ответ, иначе клиент, закрывающий окно рассинхрона query-параметрами,
// сам бы себе его и поднимал.
//
// Значения сравниваются как есть, без приведения: и в профиль, и в область действия токена
// попадает один и тот же вид - язык и пояс из списков, зарегистрированных приложением.
// Приведением здесь никто не занимается: на границе ввода принимаются только значения этих
// списков (см. wire/mrauth/config.TagLang и TagTimeZone), а usecase/user.ChangeSettings
// сохраняет их как есть.
//
// Проверяется на пустоту именно значение токена: пустое означает, что настройка в нём
// не зафиксирована, - сравнивать не с чем, и по ней признак не поднимается; вторая настройка
// при этом проверяется как обычно. Значение профиля на пустоту не проверяется намеренно:
// в профиль настройка попадает только из списков приложения (при регистрации и при смене
// настроек), поэтому пустой она там не бывает, а окажись - расхождение с токеном реально,
// и признак должен подняться.
func isSettingsPending(user entity.User, tokenLang, tokenTimeZone string) bool {
	return (tokenTimeZone != "" && user.TimeZone != tokenTimeZone) ||
		(tokenLang != "" && user.LangCode != tokenLang)
}
