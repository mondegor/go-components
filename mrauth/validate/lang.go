package validate

import (
	"regexp"
)

var regexpLang = regexp.MustCompile(`^[a-zA-Z]{2,3}([-_][a-zA-Z]{2})?$`)

// Lang - сообщает о соответствии указанного значения формату языка (локали) пользователя:
// двух- или трёхбуквенный код языка и необязательный код региона (напр. ru, ru-RU, en_US).
//
// Проверяется только форма записи, чтобы отсеять заведомый мусор; регистр и разделитель
// при этом произвольны ("ru_RU", "en-us"), т.к. клиенты присылают язык в разных записях.
//
// Поддерживается ли язык приложением, здесь не проверяется - это отдельное условие,
// которое добавляется поверх (см. wire/mrauth/config.TagLang): вход, сохраняемый в профиль,
// обязан точно совпадать с одним из языков приложения, поэтому одной проверки формы
// для него недостаточно.
func Lang(value string) bool {
	return regexpLang.MatchString(value)
}
